func dedupSortObjects(ts []Triple) []string {
	seen := map[string]bool{}
	out := []string{}
	for _, t := range ts {
		if !seen[t.O] {
			seen[t.O] = true
			out = append(out, t.O)
		}
	}
	sort.Strings(out)
	return out
}

