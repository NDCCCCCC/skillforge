// ReservedParamAsOf names the as_of key that agents MUST NOT supply: as_of
// is result metadata generated by the system (D16-B4 — datasets-registry
// period watermark + call instant). Its presence in a call's params is an
// invalid_params refusal before any SQL binding (铁律⑦ structural landing).
const ReservedParamAsOf = "as_of"

// MaxResultRows is the default per-call result-set row ceiling (Pitfall 7
// rule ② — "KPI 必须聚合非逐行" backstop against GROUP BY unique-key abuse:
// 逐客户明细伪装成 KPI). The literal is the source-grep lock target, NOT a
// config knob; a CompiledKPI.MaxRows > 0 overrides it per-KPI, 0 = this default.
// Exceeding it is ErrTooManyRows → ReasonResultTooLarge refusal (definition
// unqualified — data staff fix the file).
const MaxResultRows = 5000

// Reason-code vocabulary for structured refusals (D16-B2/B4/DATA-12).
// A Refusal is ALWAYS a tool RESULT (normal JSON the agent can read and
// re-narrate to the user), never a Go error — Go errors are reserved for
// infrastructure failures only (engine crash, audit write failure).
const (
	ReasonNoMatchingKPI        = "no_matching_kpi"
	ReasonInvalidParams        = "invalid_params"
	ReasonDatasetNotAvailable  = "dataset_not_available"
	ReasonResultTooLarge       = "result_too_large"
)

// ASOf is the system-generated result metadata (D16-B4 / 16-RESEARCH
// Pattern 5): period = the datasets registry's latest period watermark for
// the KPI's logical dataset; ts = the call moment (UTC RFC3339Nano). Both
// fields come from the SYSTEM, never from agent input — the param schema
// has no as_of field and supplying one is refused (test: TestASofAutoGenerated).
type ASOf struct {
	Period string `json:"period"`
	Ts     string `json:"ts"`
}

// Snapshot is the SINGLE SOURCE OF TRUTH for all three output legs of one
// successful call (三路输出单一真源): the tool JSON returned to the agent,
// the kpi_calls audit row (full-freeze ResultSnapshot, D16-D3), and the
// 16-08 SSE DataReference payload are all derived from THIS struct so the
// fields can never drift apart. Rows already carry k_min suppression markers.
type Snapshot struct {
	Func        string         `json:"func"`
	Args        map[string]any `json:"args"`
	ASOf        ASOf           `json:"as_of"`
	Rows        []map[string]any `json:"rows"`
	KMinApplied int            `json:"k_min_applied"`
	Suppressed  int            `json:"suppressed"`
}

// Refusal is a structured tool-result rejection (D16-B2 / DATA-12):
// reason_code ∈ {no_matching_kpi, invalid_params, dataset_not_available,
// result_too_large}; human_explanation is the constructive Chinese narration
// the agent relays verbatim-ish; available_kpis is populated ONLY for
// no_matching_kpi (sorted defensive copy of reg.Names()).
//
// IRON RULE: a Refusal is NOT a Go error. Returning a Go error would make
// eino render tool noise and the agent would never learn WHY it failed nor
// what IS available — the exact hallucination bait DATA-03/12 forbid.
type Refusal struct {
	ReasonCode       string   `json:"reason_code"`
	HumanExplanation string   `json:"human_explanation"`
	AvailableKPIs    []string `json:"available_kpis,omitempty"`
}

// CallOutcome is the executor's result pair. Exactly one leg is non-nil for
// any nil-error return; Snapshots ride data calls, Refusals ride policy
// rejections. CallOutcome{} with a non-nil error means infrastructure
// failure (engine / audit) — no snapshot, no silent degradation (T-16-06-05).
type CallOutcome struct {
	Snapshot *Snapshot
	Refusal  *Refusal
}

// DatasetVersion is the kpi package's narrow view of store.DatasetRow
// (Period/FilePath/KMinOverride only) — assembled from sqlite by the caller
// (cmd/server assembly owns the adapter; WSL tests inline one).
type DatasetVersion struct {
	// Period is the latest registered period watermark for the dataset
	// (e.g. "2026-07"). Empty means "not available" → dataset refusal.
	Period string
	// FilePath is the on-disk .duckdb location for the composite.
	FilePath string
	// KMinOverride is the per-dataset floor override (0 = defer; D15-D3).
	KMinOverride int
}

// DatasetMetaSource is the narrow seam for as_of generation (interface
// isolation, staging.go:59-65 DatasetRegistry model): internal/kpi reads
// the latest dataset version WITHOUT importing the whole store.Store.
type DatasetMetaSource interface {
	LatestDatasetVersion(ctx context.Context, dataset string) (DatasetVersion, error)
	// Periods returns all registered period watermarks for the given logical
	// dataset, sorted ascending. Used by CallMultiPeriod (D17-B3) to
	// intersect requested periods against available data.
	Periods(ctx context.Context, dataset string) ([]string, error)
}

// EngineRequest is the ONLY CGO boundary crossing for execution: the
// engine adapter receives the pre-validated $param SQL template + named
// args and performs compound-alias resolution internally. The agent NEVER
// reaches SQL text through this surface (DATA-03 execution-side lock).
type EngineRequest struct {
	Dataset string // logical dataset name (e.g. "loans")
	Period  string // resolved period watermark (e.g. "2026-07")
	// FilePath is the .duckdb file the adapter ATTACHes (from DatasetVersion).
	FilePath string
	// SQL is the compiled $param template (CompiledKPI.SQLDollar) whose table
	// references use the ds_{dataset} short alias (composite substitution is
	// the ENGINE side's job).
	SQL string
	// TableRefCount mirrors CompiledKPI.TableRefCount (16-05 AST count);
	// the adapter must replace exactly this many aliases or fail sentinel.
	TableRefCount int
	// Args are sql.NamedArg bindings built from validated params (nil value
	// bound for omitted optional params).
	Args []sql.NamedArg
	// MaxRows is the effective per-call row ceiling (executor-resolved).
	MaxRows int
}

// QueryEngine is the engine-side half of the executor seams. The production
// implementation is internal/duckdb.EngineAdapter (CGO); hermetic tests stub it.
type QueryEngine interface {
	Query(ctx context.Context, req EngineRequest) ([]map[string]any, error)
}

// AuditSink is the audit-leg seam. It imports ONLY internal/store's pure
// type face (store.KPICallRow) — CGO-free discipline preserved; the sqlite
// driver subpackage must NEVER be imported from internal/kpi (structural
// grep gate checks for that module path with count 0 in every kpi/*.go).
type AuditSink interface {
	PutKPICall(ctx context.Context, row store.KPICallRow) error
}

var (
	// ErrTooManyRows is returned by the engine adapter when the scanned row
	// count exceeds EngineRequest.MaxRows. The executor transcodes it into a
	// ReasonResultTooLarge refusal (the KPI definition is unqualified — data
	// staff fix the file; Pitfall 7 rule ②).
	ErrTooManyRows = errors.New("kpi: result set exceeds max_rows")

	// ErrAliasCountMismatch is returned by the engine adapter when the
	// controlled ds_{dataset}→ds_{dataset}__{period} replacement does not hit
	// exactly TableRefCount occurrences (template drift defense anchored to
	// the 16-05 AST walk count). The executor passes it through as an infra
	// error — it signals a definition/engine contract break, not an agent fault.
	ErrAliasCountMismatch = errors.New("kpi: composite alias replacement count mismatch")
)

// Executor orchestrates one kpi_call end-to-end (Call's six steps) over its
// four immutable collaborators. Constructed once at startup from the
// compiled Registry (closure-captured immutable snapshot — retrieve.go:113-131
// narrative); every Call reads only these references, so concurrent Calls
// share them safely.
type Executor struct {
	reg    *Registry
	meta   DatasetMetaSource
	engine QueryEngine
	audit  AuditSink
	now    func() time.Time
}

// NewExecutor wires the executor. ANY nil dependency panics immediately with
// the retrieve.go:113-122 "caller bug" convention — assembly mistakes must
// crash at boot, never lurk until the first LLM-triggered call.
func NewExecutor(reg *Registry, meta DatasetMetaSource, engine QueryEngine, audit AuditSink, now func() time.Time) *Executor {
	if reg == nil {
		panic("kpi.NewExecutor: registry is nil (caller bug)")
	}
	if meta == nil {
		panic("kpi.NewExecutor: meta source is nil (caller bug)")
	}
	if engine == nil {
		panic("kpi.NewExecutor: query engine is nil (caller bug)")
	}
	if audit == nil {
		panic("kpi.NewExecutor: audit sink is nil (caller bug)")
	}
	if now == nil {
		now = time.Now
	}
	return &Executor{reg: reg, meta: meta, engine: engine, audit: audit, now: now}
}

// CallRequest is one kpi_call invocation: the KPI name, the agent-supplied
// params, and the session/skill context stamped onto the audit row.
type CallRequest struct {
	Name      string
	Params    map[string]any
	SessionID string
	SkillID   string
}

// Call executes the six-step orchestration (godoc semantics list follows the
// CommitStagedDataset density precedent, staging.go:83-104):
//
//   - Step ① unknown name: NO-match lookup returns CallOutcome{Refusal{
//     ReasonNoMatchingKPI, Chinese explanation pointing at AvailableKPIs,
//     sorted Names()}} with NIL Go error (D16-B2: refusal = tool result;
//     DATA-12 human_explanation narrates constructively).
//   - Step ② param validation is FAIL-CLOSED BEFORE any SQL binding
//     (D16-A3/B4/T-16-06-01 first layer): as_of present → invalid_params;
//     required-missing (or explicitly-nil required), enum out-of-domain,
//     pattern mismatch, and ANY undeclared extra key each produce
//     invalid_params naming the offending param and its legal domain.
//     Refusals stay tool results (nil error).
//   - Step ③ as_of generation: LatestDatasetVersion failure OR empty Period
//     → ReasonDatasetNotAvailable refusal (defense-in-depth second layer
//     beyond bootstrap-window loading); success stamps ASOf{Period, now UTC
//     RFC3339Nano}. Agent-supplied freshness claims are structurally impossible.
//   - Step ④ engine execution: ResolveKMin(file>override>default); QueryEngine
//     runs the $param template over Args built from VALIDATED params only
//     (sql.Named second injection layer — schema-check + bind are independent
//     failures, T-16-06-01). ErrTooManyRows → ReasonResultTooLarge refusal;
//     every other engine error is an infra Go error passthrough.
//   - Step ⑤ k_min suppression: Apply replaces small-bucket VALUE columns
//     with "suppressed", retains rows/dimension/count columns (D16-D1;
//     anti-HAVING — Pitfall 4).
//   - Step ⑥ three-output emission: ONE Snapshot feeds the tool JSON, the
//     kpi_calls audit row (PutKPICall full-freeze marshal(snap) — replay
//     zero-loss, KPI-02) and the future SSE DataRef. AUDIT WRITE FAILURE IS
//     FATAL to the call: returns (CallOutcome{}, Go error) so a successful
//     answer can never lack its audit line (T-16-06-05, TestCallOutcomeAuditWrite).
//
// Concurrency: safe for concurrent use; every collaborator is read-only after
// NewExecutor and rows/maps are freshly allocated per call.
func (e *Executor) Call(ctx context.Context, req CallRequest) (CallOutcome, error) {
	// ① Unknown KPI → structured refusal, nil error (tool result).
	k, ok := e.reg.Lookup(req.Name)
	if !ok {
		return CallOutcome{Refusal: &Refusal{
			ReasonCode: ReasonNoMatchingKPI,
			HumanExplanation: fmt.Sprintf(
				"未找到名为 %q 的 KPI。只能按名调用预编译指标（不接受自定义 SQL 或即席聚合）。可用目录见 available_kpis，请检查名称后重试。",
				req.Name),
			AvailableKPIs: e.reg.Names(), // sorted defensive copy (registry contract)
		}}, nil
	}

	// ② Fail-closed parameter validation BEFORE binding (layer 1 of the
	// two-layer injection defense).
	if refusal := validateParams(k, req.Params); refusal != nil {
		return CallOutcome{Refusal: refusal}, nil
	}

	// ③ System-generated as_of (D16-B4). Meta failure / empty period →
	// dataset-not-available refusal (runtime fallback beyond load-time guard).
	version, err := e.meta.LatestDatasetVersion(ctx, k.Dataset)
	if err != nil {
		return CallOutcome{Refusal: &Refusal{
			ReasonCode: ReasonDatasetNotAvailable,
			HumanExplanation: fmt.Sprintf(
				"数据集 %q 当前不可用（注册表读取失败），无法生成可靠的数据时点说明，已拒绝本次调用；请稍后重试或联系数据管理员。",
				k.Dataset),
		}}, nil
	}
	if version.Period == "" {
		return CallOutcome{Refusal: &Refusal{
			ReasonCode: ReasonDatasetNotAvailable,
			HumanExplanation: fmt.Sprintf(
				"数据集 %q 尚无任何已注册的数据期次（bootstrap 窗口之外），无法计算该指标；请先完成该数据集的导入并提交。",
				k.Dataset),
		}}, nil
	}

	now := e.now()
	asOf := ASOf{Period: version.Period, Ts: now.UTC().Format(time.RFC3339Nano)}

	// ④ Execute via the engine adapter (only CGO crossing for execution).
	kmin := ResolveKMin(k.FileKMin, version.KMinOverride)
	maxRows := k.MaxRows
	if maxRows <= 0 {
		maxRows = MaxResultRows
	}
	engineRows, err := e.engine.Query(ctx, EngineRequest{
		Dataset:       k.Dataset,
		Period:        version.Period,
		FilePath:      version.FilePath,
		SQL:           k.SQLDollar,
		TableRefCount: k.TableRefCount,
		Args:          buildNamedArgs(k, req.Params),
		MaxRows:       maxRows,
	})
	if err != nil {
		if errors.Is(err, ErrTooManyRows) {
			return CallOutcome{Refusal: &Refusal{
				ReasonCode: ReasonResultTooLarge,
				HumanExplanation: fmt.Sprintf(
					"KPI %q 的结果集超过行数上限 %d（max_rows 定义约束）。这是 KPI 定义不合格——请联系数据管理员修正 kpis 文件（要求真正聚合而非逐行明细）。",
					req.Name, maxRows),
			}}, nil
		}
		return CallOutcome{}, fmt.Errorf("engine.Query %s: %w", req.Name, err)
	}

	// ⑤ k_min row-level suppression (Go post-filter; rows RETAINED).
	rows, suppressed := Apply(engineRows, k.CountColumn, k.PreserveColumns, kmin)

	// ⑥ Single-snapshot three-output emission.
	snap := Snapshot{
		Func:        req.Name,
		Args:        copyParams(req.Params),
		ASOf:        asOf,
		Rows:        rows,
		KMinApplied: kmin,
		Suppressed:  suppressed,
	}
	snapJSON, err := json.Marshal(snap)
	if err != nil {
		return CallOutcome{}, fmt.Errorf("marshal snapshot %s: %w", req.Name, err)
	}
	argsJSON, err := json.Marshal(snap.Args)
	if err != nil {
		return CallOutcome{}, fmt.Errorf("marshal args %s: %w", req.Name, err)
	}
	row := store.KPICallRow{
		TS:             now,
		SessionID:      req.SessionID,
		SkillID:        req.SkillID,
		Func:           req.Name,
		ArgsJSON:       string(argsJSON),
		ASOfPeriod:     asOf.Period,
		KMinApplied:    kmin,
		ResultSnapshot: string(snapJSON),
		Signature:      e.reg.Signature(),
	}
	if err := e.audit.PutKPICall(ctx, row); err != nil {
		// Audit-failed ⇒ call FAILED (T-16-06-05): a successful answer without
		// its frozen audit line breaks the replay promise (KPI-02).
		return CallOutcome{}, fmt.Errorf("audit.PutKPICall %s: %w", req.Name, err)
	}
	return CallOutcome{Snapshot: &snap}, nil
}

// CallMultiPeriod executes kpi_call for N periods in a single invocation.
// Mirrors Call's six steps, but loops over N periods and merges rows tagged
// with the period column (D17-B3).
//
// Steps:
//   - ①+② same as Call (unknown KPI, param validation including array shape)
//   - ③ resolve N period watermarks via ResolvePeriods
//   - ④ loop engine.Query once per period, tag each row with period column
//   - ⑤ k_min suppression applied per-row (shared KMinApplied)
//   - ⑥ single Snapshot with merged rows + sorted periods in Args
func (e *Executor) CallMultiPeriod(ctx context.Context, req CallRequest) (CallOutcome, error) {
	// ① Unknown KPI → structured refusal (same as Call).
	k, ok := e.reg.Lookup(req.Name)
	if !ok {
		return CallOutcome{Refusal: &Refusal{
			ReasonCode: ReasonNoMatchingKPI,
			HumanExplanation: fmt.Sprintf(
				"未找到名为 %q 的 KPI。只能按名调用预编译指标（不接受自定义 SQL 或即席聚合）。可用目录见 available_kpis，请检查名称后重试。",
				req.Name),
			AvailableKPIs: e.reg.Names(),
		}}, nil
	}

	// ② Fail-closed parameter validation (including array shape).
	if refusal := validateParams(k, req.Params); refusal != nil {
		return CallOutcome{Refusal: refusal}, nil
	}

	// Extract periods []string from validated params.
	rawPeriods, ok := req.Params["periods"].([]any)
	if !ok {
		return CallOutcome{Refusal: &Refusal{
			ReasonCode: ReasonInvalidParams,
			HumanExplanation: "periods 参数必须是数组类型。",
		}}, nil
	}
	reqPeriods := make([]string, len(rawPeriods))
	for i, rp := range rawPeriods {
		reqPeriods[i], ok = rp.(string)
		if !ok {
			return CallOutcome{Refusal: &Refusal{
				ReasonCode: ReasonInvalidParams,
				HumanExplanation: fmt.Sprintf("periods[%d] 必须是字符串类型。", i),
			}}, nil
		}
	}

	// ③ Resolve N period watermarks.
	periods, ref := ResolvePeriods(ctx, e.meta, k.Dataset, reqPeriods)
	if ref != nil {
		return CallOutcome{Refusal: ref}, nil
	}

	// Determine as_of: use the maximum period as the primary reference.
	maxPeriod := periods[len(periods)-1]

	// ④ Loop engine.Query per period, tag rows with period column.
	kmin := ResolveKMin(k.FileKMin, 0) // dataset-level override not available here; use file default
	maxRows := k.MaxRows
	if maxRows <= 0 {
		maxRows = MaxResultRows
	}

	var allRows []map[string]any
	totalSuppressed := 0
	for _, period := range periods {
		// Get FilePath for this specific period via LatestDatasetVersion
		// (requires a meta source that can scope to period — we use
		// LatestDatasetVersion as a proxy; the actual period resolution
		// was done in ResolvePeriods, so the dataset must be registered).
		version, err := e.meta.LatestDatasetVersion(ctx, k.Dataset)
		if err != nil {
			return CallOutcome{}, fmt.Errorf("engine.Query %s period %s: %w", req.Name, period, err)
		}
		// Build per-period request, replacing periods:[...] with single period.
		periodParams := copyParams(req.Params)
		periodParams["period"] = period
		engineRows, err := e.engine.Query(ctx, EngineRequest{
			Dataset:       k.Dataset,
			Period:        period,
			FilePath:      version.FilePath,
			SQL:           k.SQLDollar,
			TableRefCount: k.TableRefCount,
			Args:          buildNamedArgs(k, periodParams),
			MaxRows:       maxRows,
		})
		if err != nil {
			if errors.Is(err, ErrTooManyRows) {
				return CallOutcome{Refusal: &Refusal{
					ReasonCode: ReasonResultTooLarge,
					HumanExplanation: fmt.Sprintf(
						"KPI %q 的结果集超过行数上限 %d（max_rows 定义约束）。",
						req.Name, maxRows),
				}}, nil
			}
			return CallOutcome{}, fmt.Errorf("engine.Query %s period %s: %w", req.Name, period, err)
		}
		// Tag each row with its period.
		for _, row := range engineRows {
			row["period"] = period
			allRows = append(allRows, row)
		}
	}

	// ⑤ k_min row-level suppression on merged rows.
	rows, suppressed := Apply(allRows, k.CountColumn, k.PreserveColumns, kmin)
	totalSuppressed += suppressed

	// ⑥ Single-snapshot three-output emission.
	now := e.now()
	asOf := ASOf{Period: maxPeriod, Ts: now.UTC().Format(time.RFC3339Nano)}
	snap := Snapshot{
		Func:        req.Name,
		Args:        copyParams(req.Params),
		ASOf:        asOf,
		Rows:        rows,
		KMinApplied: kmin,
		Suppressed:  totalSuppressed,
	}
	snapJSON, err := json.Marshal(snap)
	if err != nil {
		return CallOutcome{}, fmt.Errorf("marshal snapshot %s: %w", req.Name, err)
	}
	argsJSON, err := json.Marshal(snap.Args)
	if err != nil {
		return CallOutcome{}, fmt.Errorf("marshal args %s: %w", req.Name, err)
	}
	row := store.KPICallRow{
		TS:             now,
		SessionID:      req.SessionID,
		SkillID:        req.SkillID,
		Func:           req.Name,
		ArgsJSON:       string(argsJSON),
		ASOfPeriod:     asOf.Period,
		KMinApplied:    kmin,
		ResultSnapshot: string(snapJSON),
		Signature:      e.reg.Signature(),
	}
	if err := e.audit.PutKPICall(ctx, row); err != nil {
		return CallOutcome{}, fmt.Errorf("audit.PutKPICall %s: %w", req.Name, err)
	}
	return CallOutcome{Snapshot: &snap}, nil
}

// validateParams applies the fail-closed whitelist BEFORE any SQL binding.
// Returns a Refusal for the FIRST violation class found (aggregating its
// instances), or nil when every declared constraint holds:
//
//  1. reserved as_of key present → invalid_params (D16-B4 enforcement)
//  2. required param missing / explicitly nil
//  3. enum value outside EnumValues (non-string values also violate)
//  4. string+Pattern regex mismatch
//  5. ANY undeclared extra key (fail-closed full coverage — unknown params
//     can never smuggle past schema checking)
//
// Every branch's human_explanation names the offending parameter AND its
// legal domain (DATA-12: the agent must be able to self-correct or narrate).
func validateParams(k CompiledKPI, params map[string]any) *Refusal {
	refuse := func(detail string) *Refusal {
		return &Refusal{
			ReasonCode: ReasonInvalidParams,
			HumanExplanation: fmt.Sprintf(
				"参数校验失败：%s 请核对参数名与取值后重试（每个参数的类型、必填性与值域由受控 kpis 文件声明）。",
				detail),
		}
	}

	// 1. Reserved metadata key — system generates as_of (D16-B4).
	if _, present := params[ReservedParamAsOf]; present {
		return refuse(fmt.Sprintf(
			"不允许提供参数 %q：as_of 由系统在调用时刻自动生成（数据期次水位 + 调用时间戳），不可伪造。", ReservedParamAsOf))
	}

	declared := k.Params

	// 2+3+4. Per-declared-param checks in SORTED order for determinism.
	names := make([]string, 0, len(declared))
	for n := range declared {
		names = append(names, n)
	}
	sort.Strings(names)

	var missing []string
	for _, n := range names {
		cp := declared[n]
		v, present := params[n]
		if cp.Required && (!present || v == nil) {
			missing = append(missing, n)
			continue
		}
		if !present || v == nil {
			continue // optional omitted/nil → binds NULL downstream
		}
		switch cp.Type {
		case ParamTypeEnum:
			s, isStr := v.(string)
			if !isStr || !containsString(cp.EnumValues, s) {
				legal := strings.Join(cp.EnumValues, "、")
				return refuse(fmt.Sprintf(
					"参数 %q 取值 %v 不在合法枚举集合内（合法值：%s）。", n, v, legal))
			}
		case ParamTypeString:
			s, isStr := v.(string)
			if !isStr {
				return refuse(fmt.Sprintf("参数 %q 必须是字符串类型。", n))
			}
			if cp.Pattern != nil && !cp.Pattern.MatchString(s) {
				return refuse(fmt.Sprintf(
					"参数 %q 取值 %q 不匹配声明的格式约束（pattern: %s）。", n, s, cp.Pattern.String()))
			}
		case ParamTypeArray:
			arr, isArr := v.([]any)
			if !isArr {
				return refuse(fmt.Sprintf("参数 %q 必须是数组类型。", n))
			}
			if cp.Items == nil {
				return refuse(fmt.Sprintf("参数 %q 声明为数组但未提供 items 定义。", n))
			}
			if cp.Items.MinItems > 0 && len(arr) < cp.Items.MinItems {
				return refuse(fmt.Sprintf(
					"参数 %q 数组长度 %d 低于最小要求 %d。", n, len(arr), cp.Items.MinItems))
			}
			if cp.Items.MaxItems > 0 && len(arr) > cp.Items.MaxItems {
				return refuse(fmt.Sprintf(
					"参数 %q 数组长度 %d 超过最大限制 %d。", n, len(arr), cp.Items.MaxItems))
			}
			for i, elem := range arr {
				s, isStr := elem.(string)
				if !isStr {
					return refuse(fmt.Sprintf("参数 %q[%d] 必须是字符串类型。", n, i))
				}
				if cp.Items.PatternRE != nil && !cp.Items.PatternRE.MatchString(s) {
					return refuse(fmt.Sprintf(
						"参数 %q[%d] 取值 %q 不匹配格式约束（%s）。", n, i, s, cp.Items.PatternRE.String()))
				}
			}
		default:
			// Unreachable: loader rejects foreign types fail-closed (D16-A3).
			return refuse(fmt.Sprintf("参数 %q 类型未知（%s）——定义文件错误，请通知数据管理员。", n, cp.Type))
		}
	}
	if len(missing) > 0 {
		sort.Strings(missing)
		return refuse(fmt.Sprintf("缺少必填参数：%s。", strings.Join(missing, "、")))
	}

	// 5. Undeclared extra keys — nothing passes unchecked.
	var extras []string
	for key := range params {
		if _, ok := declared[key]; !ok {
			extras = append(extras, key)
		}
	}
	if len(extras) > 0 {
		sort.Strings(extras)
		allowed := names
		if len(allowed) == 0 {
			allowed = []string{"（本 KPI 无参数）"}
		}
		return refuse(fmt.Sprintf(
			"包含未声明的多余参数：%s（仅接受：%s）。", strings.Join(extras, "、"), strings.Join(allowed, "、")))
	}
	return nil
}

// buildNamedArgs converts validated params into deterministic sql.NamedArg
// bindings: one entry per DECLARED param (sorted), value passed through
// as-is; omitted optional params bind nil ($param IS NULL guards in SQL).
// Only validated keys reach here — schema check and binding are the two
// INDEPENDENT layers of injection defense (T-16-06-01).
func buildNamedArgs(k CompiledKPI, params map[string]any) []sql.NamedArg {
	names := make([]string, 0, len(k.Params))
	for n := range k.Params {
		names = append(names, n)
	}
	sort.Strings(names)
	args := make([]sql.NamedArg, 0, len(names))
	for _, n := range names {
		if v, ok := params[n]; ok && v != nil {
			args = append(args, sql.Named(n, v))
		} else {
			args = append(args, sql.Named(n, nil))
		}
	}
	return args
}

// copyParams shallow-copies the param map so the frozen Snapshot cannot be
// mutated retroactively through the caller's map reference.
func copyParams(params map[string]any) map[string]any {
	out := make(map[string]any, len(params))
	for k, v := range params {
		out[k] = v
	}
	return out
}

func containsString(list []string, want string) bool {
	for _, s := range list {
		if s == want {
			return true
		}
	}
	return false
}
